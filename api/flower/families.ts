export const SURFACE_LISTS = [
  "textures",
  "edges",
  "veins",
  "patterns",
  "colors",
] as const satisfies readonly ListName[];

const opensUnder: Record<Strangeness, (listName: ListName) => boolean> = {
  faithful: () => false,
  stylized: listName => isVariant(SURFACE_LISTS, listName),
  invented: () => true,
};

export function legalList<K extends ListName>(
  profile: FamilyProfile,
  strangeness: Strangeness,
  listName: K,
): FamilyLists[K] {
  return opensUnder[strangeness](listName)
    ? FULL_LISTS[listName]
    : profile[listName];
}

