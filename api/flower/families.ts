export type Rgba = { r: number; g: number; b: number; a: number };

export const round3 = (value: number): number =>
  Math.round(value * 1000) / 1000;

export function hexToRgba(hex: string): Rgba {
  const value = parseInt(hex.slice(1), 16);
  return {
    r: round3(((value >> 16) & 0xff) / 255),
    g: round3(((value >> 8) & 0xff) / 255),
    b: round3((value & 0xff) / 255),
    a: 1,
  };
}

export function darken(color: Rgba, factor: number): Rgba {
  return {
    r: round3(color.r * factor),
    g: round3(color.g * factor),
    b: round3(color.b * factor),
    a: color.a,
  };
}

